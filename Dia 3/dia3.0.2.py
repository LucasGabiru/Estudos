soma = 0

for numero in range(1, 101):
    soma += numero  # O mesmo que: soma = soma + numero

print(f"A soma de todos os números de 1 a 100 é: {soma}")

multiplicacao = 1

for numero in range(1, 101):
    multiplicacao *= numero 

print(f"A Multiplicacao de todos os numeros de 1 a 100 e {multiplicacao}")

