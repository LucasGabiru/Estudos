print("A subtração de " + str(numero1) + " e " + str(numero2) + " é igual a " + str(subtracao) + ".")
multiplicacao = numero1 * numero2
print("A multiplicação de " + str(numero1) + " e " + str(numero2) + " é igual a " + str(multiplicacao) + ".")
divisao = numero1 / numero2
print("A divisão de " + str(numero1) + " e " + str(numero2) + " é igual a " + str(divisao) + ".")